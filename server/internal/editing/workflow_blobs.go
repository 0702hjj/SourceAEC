package editing

import (
	"encoding/json"
	"errors"
	"os"
	"sort"

	"ifcviewer/server/internal/workflow"
)

type workflowInput struct {
	Path string       `json:"path"`
	Ref  workflow.Ref `json:"ref"`
}
type workflowFile struct {
	Path string       `json:"path"`
	Ref  workflow.Ref `json:"ref"`
}
type workflowCandidate struct {
	Definition  string         `json:"definition"`
	Environment string         `json:"environment"`
	Files       []workflowFile `json:"files"`
}

func (o *operation) putWorkflowBlob(data []byte) (workflow.Ref, error) {
	ref := workflow.Ref{Key: o.key("workflows/blobs/" + digest(data)), SHA256: digest(data), Bytes: int64(len(data))}
	// Reuse valid immutable content without rereading its payload.
	hash, size, err := o.runtime.StoredArtifactHash(o.ctx, o.service.Root, o.tx, ref.Key)
	if err == nil {
		if hash == ref.SHA256 && size == ref.Bytes {
			return ref, nil
		}
		// Regenerated bytes have the key's exact digest. Restore corrupted
		// storage, but never replace a valid content-addressed value.
	}
	if err != nil && !os.IsNotExist(err) {
		return ref, err
	}
	err = o.runtime.StoreWorkflowBlob(o.ctx, o.service.Root, o.tx, o.model, ref, data)
	return ref, err
}
func (o *operation) getWorkflowBlob(ref workflow.Ref, limit int64) ([]byte, error) {
	if err := workflow.ValidateRef(o.model, ref); err != nil {
		return nil, err
	}
	if ref.Bytes > limit {
		return nil, errors.New("workflow blob exceeds role limit")
	}
	size, err := o.runtime.StoredArtifactSize(o.ctx, o.service.Root, o.tx, ref.Key)
	if err != nil {
		return nil, err
	}
	if size != ref.Bytes {
		return nil, errors.New("workflow blob size changed")
	}
	data, err := o.runtime.ReadStoredArtifact(o.ctx, o.service.Root, o.tx, ref.Key)
	if err == nil && digest(data) != ref.SHA256 {
		err = errors.New("workflow blob digest changed")
	}
	return data, err
}
func (o *operation) putWorkflowJSON(value any) (workflow.Ref, error) {
	data, err := json.Marshal(value)
	if err != nil {
		return workflow.Ref{}, err
	}
	if len(data) > 1<<20 {
		return workflow.Ref{}, errors.New("workflow manifest exceeds limit")
	}
	return o.putWorkflowBlob(data)
}
func (o *operation) loadCandidate(r workflow.Run, plan *capturedExecution) (*builtExecution, error) {
	if r.Candidate == nil {
		return nil, errors.New("workflow checkpoint missing")
	}
	data, err := o.getWorkflowBlob(*r.Candidate, 1<<20)
	if err != nil {
		return nil, err
	}
	var manifest workflowCandidate
	if err = json.Unmarshal(data, &manifest); err != nil {
		return nil, err
	}
	expected := map[string]int64{
		"uploads/" + o.model + "." + o.service.Kind: productLimit,
		o.key("current.map.json"):                   sourceMapLimit, o.key("current.build.json"): 1 << 20,
		o.key("current.inputs.json"): 384 << 20, "uploads/" + o.model + "." + o.service.Kind + ".build.json": 1 << 20,
	}
	if o.service.Kind == "dxf" {
		expected[o.key("render.json")] = 128 << 20
	}
	if manifest.Definition != r.Definition || len(manifest.Files) != len(expected) {
		return nil, errors.New("invalid workflow checkpoint file set")
	}
	files := map[string][]byte{}
	seen := map[string]bool{}
	for _, file := range manifest.Files {
		limit, ok := expected[file.Path]
		if !ok || seen[file.Path] {
			return nil, errors.New("invalid workflow checkpoint path")
		}
		seen[file.Path] = true
		files[file.Path], err = o.getWorkflowBlob(file.Ref, limit)
		if err != nil {
			return nil, err
		}
	}
	product := Product{Data: files["uploads/"+o.model+"."+o.service.Kind], Map: files[o.key("current.map.json")], Environment: manifest.Environment}
	if err := validateProduct(product.Data, o.service.Kind); err != nil {
		return nil, err
	}
	mapping, err := parseSourceMap(product.Map)
	if err != nil {
		return nil, err
	}
	if mapping.Hash != digest([]byte(plan.script)) {
		return nil, errors.New("workflow source map revision mismatch")
	}
	var build struct{ ScriptHash, ProductHash, InputsHash, Environment, Kind string }
	if err := json.Unmarshal(files[o.key("current.build.json")], &build); err != nil {
		return nil, err
	}
	if build.ScriptHash != digest([]byte(plan.script)) || build.ProductHash != digest(product.Data) || build.InputsHash != digest(files[o.key("current.inputs.json")]) || build.Environment != product.Environment || build.Kind != o.service.Kind {
		return nil, errors.New("workflow candidate provenance mismatch")
	}
	if digest(files[o.key("current.build.json")]) != digest(files["uploads/"+o.model+"."+o.service.Kind+".build.json"]) {
		return nil, errors.New("workflow build identity mismatch")
	}
	return &builtExecution{plan: plan, product: product, files: files}, nil
}
func (o *operation) checkpointFiles(built *builtExecution, definition string) (workflow.Ref, error) {
	manifest := workflowCandidate{Environment: built.product.Environment, Definition: definition}
	keys := make([]string, 0, len(built.files))
	for key := range built.files {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	for _, key := range keys {
		ref, err := o.putWorkflowBlob(built.files[key])
		if err != nil {
			return workflow.Ref{}, err
		}
		manifest.Files = append(manifest.Files, workflowFile{key, ref})
	}
	return o.putWorkflowJSON(manifest)
}
